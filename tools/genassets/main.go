package main

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

// 本生成器把内嵌资产加密后固化到 internal/assets/data_gen.go。
//
// 【为什么不是明文】提示词与 TAMPER 规则含红队术语，明文躺在 .rdata 会被
// Defender/火绒的启发式静态扫描误报（如 Backdoor/CobaltStrike）。
//
// 【为什么不是 XOR 了（2026-10 audit）】旧版用 11 字节重复 XOR，密钥
// "xAntiGlance" 硬编码在生成器和产出文件里 —— 等于没加密，只是把明文
// 换成"看起来像密文"的字节。现在改为 AES-256-GCM：
//
//	K = SHA-256(HELMX_ASSET_KEY or devKeySeed)
//
// 密钥来源外部化：构建时设 HELMX_ASSET_KEY，二进制里只留 SHA-256(K) 摘要，
// 不落密钥本身；运行时用同样的环境变量重算，摘要不符即判定"构建/运行密钥
// 不一致"并明确失败，而不是静默降级成空提示词。
//
// 诚实声明：这不是安全边界（本地工具防不住逆向，密钥最终要进内存），
// 目标是 (1) strings 看不到明文 (2) 密钥不随仓库分发 (3) 换 key 不必改代码。
const devKeySeed = "helm-x-dev-asset-key-do-not-ship"

var targetFiles = []string{
	"data/prompt-v2.1.md",
	"data/prompt-v4.md",
	"data/prompt-v5.md",
	"data/prompt-v6.md",
	"data/prompt-mdx61.md",
	"data/prompt-seagull.md",
	"data/prompt-xiaoliu.md",
	"data/prompt-xwsandbox.md",
	"data/prompt-chang.md",
	"data/prompt-v2.md",
	"data/prompt-ctf-scoring.md",
	"data/tamper_rules.txt",
	"data/rewrite_prompt.txt",
	"data/qa.json",
}

func main() {
	baseDir := filepath.Join("internal", "assets")
	if _, err := os.Stat(filepath.Join(baseDir, "data")); err != nil {
		if _, err := os.Stat("data"); err == nil {
			baseDir = "."
		} else {
			baseDir = filepath.Join("..", "..", "internal", "assets")
		}
	}

	seed := os.Getenv("HELMX_ASSET_KEY")
	fromEnv := seed != ""
	if !fromEnv {
		seed = devKeySeed
	}
	key := sha256.Sum256([]byte(seed))
	digest := sha256.Sum256(key[:])

	block, err := aes.NewCipher(key[:])
	if err != nil {
		fail("构造 AES: %v", err)
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		fail("构造 GCM: %v", err)
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/genassets; DO NOT EDIT.\n\n")
	buf.WriteString("package assets\n\n")
	buf.WriteString("// assetKeyDigest 是构建期密钥 K=SHA-256(seed) 的摘要（不是 K 本身）。\n")
	buf.WriteString("// 运行期用同样种子重算 K 并比对摘要：不符即说明构建用了外部密钥而运行时没提供。\n")
	buf.WriteString("var assetKeyDigest = []byte{")
	writeBytes(&buf, digest[:])
	buf.WriteString("}\n\n")
	buf.WriteString("// assetKeyFromEnv 记录构建时是否提供了 HELMX_ASSET_KEY。\n")
	buf.WriteString(fmt.Sprintf("const assetKeyFromEnv = %v\n\n", fromEnv))
	buf.WriteString("// obfuscatedData 是 nonce||GCM 密文。\n")
	buf.WriteString("var obfuscatedData = map[string][]byte{\n")

	for _, relPath := range targetFiles {
		fullPath := filepath.Join(baseDir, relPath)
		raw, err := os.ReadFile(fullPath)
		if err != nil {
			fail("读取 %s: %v", fullPath, err)
		}
		nonce := make([]byte, gcm.NonceSize())
		if _, err := rand.Read(nonce); err != nil {
			fail("生成 nonce: %v", err)
		}
		blob := gcm.Seal(nonce, nonce, raw, []byte(relPath)) // AAD = 逻辑路径，防张冠李戴

		key := filepath.ToSlash(relPath)
		buf.WriteString(fmt.Sprintf("\t%q: {\n\t\t", key))
		writeBytesBody(&buf, blob)
		buf.WriteString("\n\t},\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fail("格式化产物: %v", err)
	}
	outPath := filepath.Join(baseDir, "data_gen.go")
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		fail("写入 %s: %v", outPath, err)
	}
	src := "内置默认种子"
	if fromEnv {
		src = "HELMX_ASSET_KEY"
	}
	fmt.Printf("assets: %d 个文件 → %s（密钥来源：%s）\n", len(targetFiles), outPath, src)
}

func writeBytes(buf *bytes.Buffer, b []byte) {
	for i, x := range b {
		if i > 0 {
			buf.WriteString(", ")
		}
		buf.WriteString(fmt.Sprintf("0x%02x", x))
	}
}

func writeBytesBody(buf *bytes.Buffer, b []byte) {
	for i, x := range b {
		buf.WriteString(fmt.Sprintf("0x%02x, ", x))
		if (i+1)%16 == 0 && i+1 < len(b) {
			buf.WriteString("\n\t\t")
		}
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genassets: "+format+"\n", args...)
	os.Exit(1)
}
